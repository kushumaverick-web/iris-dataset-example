import sqlite3

# 1. Connect to the database (creates 'school.db')
conn = sqlite3.connect('school.db')
cursor = conn.cursor()

# 2. Create the students table
cursor.execute('''
    CREATE TABLE IF NOT EXISTS students (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        major TEXT NOT NULL,
        gpa REAL
    )
''')

# Clear out any old entries so we start fresh with your data
cursor.execute('DELETE FROM students')

# 3. Insert your custom student records
sample_students = [
    ('kush', 'Data Science', 9.8),
    ('yadu', 'Cybersecurity', 8.4),
    ('dev', 'Computer Science', 6.6),
    ('sumit', 'MCA', 8.8),
    ('anand', 'forensic science', 4.7)
]
cursor.executemany("INSERT INTO students (name, major, gpa) VALUES (?, ?, ?)", sample_students)

# Commit (save) the changes permanently
conn.commit()

# 4. Query and display all records from the database
cursor.execute("SELECT id, name, major, gpa FROM students")
rows = cursor.fetchall()

print("--- Custom Students Database Records ---")
for row in rows:
    student_id, name, major, gpa = row
    print(f"ID: {student_id} | Name: {name:<8} | Major: {major:<18} | GPA: {gpa}")

# Perform the query for 'Data Science' students before closing the connection
cursor.execute("SELECT name, major, gpa FROM students WHERE major = 'Data Science'")
data_science_students = cursor.fetchall()

print("\n--- Data Science Students ---")
if data_science_students:
    for student in data_science_students:
        print(f"Name: {student[0]:<8} | Major: {student[1]:<18} | GPA: {student[2]}")
else:
    print("No Data Science students found.")

# 5. Close the connection safely